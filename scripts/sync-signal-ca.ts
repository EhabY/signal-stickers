import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUTPUT = "packages/core/src/net/signalCa.ts";

const [signalDesktopDir] = process.argv.slice(2);
if (signalDesktopDir === undefined) {
	console.error("Usage: node scripts/sync-signal-ca.ts <Signal-Desktop dir>");
	process.exit(1);
}

const config: unknown = JSON.parse(
	readFileSync(join(signalDesktopDir, "config", "default.json"), "utf8"),
);
if (
	typeof config !== "object" ||
	config === null ||
	!("certificateAuthority" in config) ||
	typeof config.certificateAuthority !== "string"
) {
	throw new Error("config/default.json has no certificateAuthority");
}
const lines = config.certificateAuthority
	.trim()
	.split("\n")
	.map((line) => `\t"${line}",`);

writeFileSync(
	OUTPUT,
	[
		"// Generated by scripts/sync-signal-ca.ts from Signal-Desktop's config/default.json.",
		"export const SIGNAL_CA = [",
		...lines,
		String.raw`].join("\n");`,
		"",
	].join("\n"),
);
console.log(`Wrote ${OUTPUT}`);
